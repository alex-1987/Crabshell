#!/usr/bin/env python3
"""Generate src/theme-palette.css from the colors used in src/styles.css.

Every hex color in styles.css is replaced by `var(--c-<hex>)`. The dark theme keeps
the original value; the light theme inverts the HSL lightness (hue and saturation
stay), so the palette keeps its character with readable contrast on light surfaces.
Near-black colors with alpha (shadows, scrims) are left unchanged in both themes.

Run again after adding new hex colors to styles.css:  python3 scripts/gen-theme-palette.py
"""
import colorsys
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
STYLES = ROOT / "src" / "styles.css"
PALETTE = ROOT / "src" / "theme-palette.css"
HEX = re.compile(r"#([0-9a-fA-F]{8}|[0-9a-fA-F]{6}|[0-9a-fA-F]{4}|[0-9a-fA-F]{3})\b")


def expand(value: str) -> str:
    value = value.lower()
    return "".join(ch * 2 for ch in value) if len(value) in (3, 4) else value


def light_variant(value: str) -> str:
    rgb, alpha = value[:6], value[6:]
    r, g, b = (int(rgb[i : i + 2], 16) / 255 for i in (0, 2, 4))
    h, lightness, s = colorsys.rgb_to_hls(r, g, b)
    if alpha and lightness < 0.05:
        return value  # shadow / scrim
    # Invert lightness, nudged so surfaces are not pure white and text not pure black.
    lightness = 0.04 + (1 - lightness) * 0.93
    r, g, b = colorsys.hls_to_rgb(h, lightness, s)
    return "".join(f"{round(c * 255):02x}" for c in (r, g, b)) + alpha


def main() -> None:
    css = STYLES.read_text()
    # Variables already converted are kept; only raw hex literals are replaced.
    colors = {expand(m.group(1)) for m in HEX.finditer(css)}
    existing = set(re.findall(r"--c-([0-9a-f]{6,8}):", PALETTE.read_text())) if PALETTE.exists() else set()
    colors |= existing
    css = HEX.sub(lambda m: f"var(--c-{expand(m.group(1))})", css)
    STYLES.write_text(css)

    names = sorted(colors)
    dark = "\n".join(f"  --c-{c}: #{c};" for c in names)
    light = "\n".join(f"  --c-{c}: #{light_variant(c)};" for c in names)
    PALETTE.write_text(
        "/* Generated by scripts/gen-theme-palette.py - edit styles.css, then rerun the script. */\n"
        f":root {{\n  color-scheme: dark;\n{dark}\n}}\n\n"
        f':root[data-theme="light"] {{\n  color-scheme: light;\n{light}\n}}\n'
    )
    print(f"{len(names)} colors written to {PALETTE.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
